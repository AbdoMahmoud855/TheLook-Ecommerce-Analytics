import os

SOURCE = "bigquery-public-data.thelook_ecommerce"

TABLES = [
    "distribution_centers",
    "events",
    "inventory_items",
    "order_items",
    "orders",
    "products",
    "users"
]

OUTPUT_DIR = "/content/TheLook_Ecommerce"

os.makedirs(OUTPUT_DIR, exist_ok=True)

from tqdm.auto import tqdm

CHUNK_SIZE = 100_000

for table_name in TABLES:

    print(f"\nDownloading {table_name}...")

    output_file = f"{OUTPUT_DIR}/{table_name}.csv"

    if table_name == "users":
        sql = f"""
        SELECT *,
               ST_ASTEXT(user_geom) AS user_geom_wkt
        FROM `{SOURCE}.{table_name}`
        """

        # Avoid duplicate original GEOGRAPHY column
        sql = f"""
        SELECT
            * EXCEPT(user_geom),
            ST_ASTEXT(user_geom) AS user_geom
        FROM `{SOURCE}.{table_name}`
        """

    elif table_name == "distribution_centers":
        sql = f"""
        SELECT
            * EXCEPT(distribution_center_geom),
            ST_ASTEXT(distribution_center_geom)
                AS distribution_center_geom
        FROM `{SOURCE}.{table_name}`
        """

    else:
        sql = f"SELECT * FROM `{SOURCE}.{table_name}`"

    query_job = client.query(sql)
    rows = query_job.result(page_size=CHUNK_SIZE)

    first_chunk = True
    total_rows = 0

    for df in rows.to_dataframe_iterable():

        df.to_csv(
            output_file,
            index=False,
            mode="w" if first_chunk else "a",
            header=first_chunk
        )

        total_rows += len(df)
        first_chunk = False

    print(f"Completed: {total_rows:,} rows")

